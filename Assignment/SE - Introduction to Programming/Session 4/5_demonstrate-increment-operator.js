// Write a code snippet that demonstrates the difference between pre-increment (++count) and post-increment (count++) 
// by logging the values before and after using both on a followerCount variable.

let followerCount = 200;

console.log("Starting value: ", followerCount);

console.log("Pre-increment result: ", ++followerCount);
console.log("Current value: ", followerCount);

console.log("Post-increment result: ", followerCount++);
console.log("Current value: ", followerCount);
